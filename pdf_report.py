"""Builds a simple one-table PDF report without any extra libraries."""

import textwrap
import zlib


PAGE_WIDTH = 595   # A4, in points
PAGE_HEIGHT = 842
MARGIN = 40

PRIMARY = (0.055, 0.486, 0.525)
TEXT = (0.122, 0.161, 0.216)
MUTED = (0.420, 0.447, 0.502)
ROW_BG = (0.953, 0.957, 0.965)
BORDER = (0.898, 0.906, 0.922)

LABEL_X = MARGIN + 14
VALUE_X = MARGIN + 190
VALUE_CHARS = 48   # characters per line before a value wraps
LINE_HEIGHT = 15
TABLE_TOP = PAGE_HEIGHT - 175
TABLE_BOTTOM = 80


def pdf_text(text):
    # Built-in PDF fonts only cover Latin-1; escape PDF string delimiters
    text = str(text).encode("latin-1", "replace").decode("latin-1")
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def color(rgb, stroke=False):
    return "%.3f %.3f %.3f %s" % (*rgb, "RG" if stroke else "rg")


def text_op(x, y, text, font="F1", size=11, rgb=TEXT):
    return "BT /%s %d Tf %s %.1f %.1f Td (%s) Tj ET" % (
        font, size, color(rgb), x, y, pdf_text(text)
    )


def page_header(title, subtitle, info, generated, heading):
    top = PAGE_HEIGHT - 80
    ops = [
        color(PRIMARY),
        "0 %d %d 80 re f" % (top, PAGE_WIDTH),
        text_op(MARGIN, top + 44, title, "F2", 20, (1, 1, 1)),
    ]
    if subtitle:
        ops.append(text_op(MARGIN, top + 24, subtitle, "F1", 11, (1, 1, 1)))
    if info:
        ops.append(text_op(MARGIN, top - 28, info, "F2", 11, TEXT))
    ops += [
        text_op(MARGIN, top - (46 if info else 28), generated, "F1", 10, MUTED),
        text_op(MARGIN, TABLE_TOP + 12, heading, "F2", 14, TEXT),
    ]
    return ops


def page_footer(page_number, page_count):
    return [
        color(BORDER, stroke=True),
        "0.8 w %d 60 m %d 60 l S" % (MARGIN, PAGE_WIDTH - MARGIN),
        text_op(MARGIN, 44, "Generated by the USC-V1 app", "F1", 9, MUTED),
        text_op(PAGE_WIDTH - MARGIN - 60, 44,
                "Page %d of %d" % (page_number, page_count), "F1", 9, MUTED),
    ]


def layout_rows(rows):
    # Split the rows over pages; each value may wrap onto several lines
    pages = [[]]
    y = TABLE_TOP

    for index, (label, value) in enumerate(rows):
        lines = textwrap.wrap(str(value), VALUE_CHARS) or [""]
        height = 14 + LINE_HEIGHT * len(lines)

        if y - height < TABLE_BOTTOM and pages[-1]:
            pages.append([])
            y = TABLE_TOP

        pages[-1].append((index, label, lines, y, height))
        y -= height

    return pages


def draw_row(index, label, lines, y, height):
    ops = []
    if index % 2 == 0:
        ops += [color(ROW_BG),
                "%d %.1f %d %.1f re f" % (MARGIN, y - height,
                                          PAGE_WIDTH - 2 * MARGIN, height)]

    first_line = y - 7 - 11
    ops.append(text_op(LABEL_X, first_line, label, "F1", 11, MUTED))
    for number, line in enumerate(lines):
        ops.append(text_op(VALUE_X, first_line - number * LINE_HEIGHT,
                           line, "F2", 11, TEXT))
    return ops


def build_pdf(rows, title, subtitle, info, generated, heading):
    """rows: list of (label, value). Returns the PDF file as bytes.

    title/subtitle go in the coloured header band, info and generated
    below it, and heading above the table. Empty subtitle/info are skipped.
    """

    pages = layout_rows(rows)
    streams = []

    for number, page_rows in enumerate(pages, start=1):
        ops = page_header(title, subtitle, info, generated, heading)

        if page_rows:
            top = page_rows[0][3]
            bottom = page_rows[-1][3] - page_rows[-1][4]
            for row in page_rows:
                ops += draw_row(*row)
            ops += [color(BORDER, stroke=True),
                    "0.8 w %d %.1f %d %.1f re S" % (
                        MARGIN, bottom, PAGE_WIDTH - 2 * MARGIN, top - bottom)]
        else:
            ops.append(text_op(MARGIN, TABLE_TOP - 20, "No data received.",
                               "F1", 11, MUTED))

        ops += page_footer(number, len(pages))
        streams.append("\n".join(ops).encode("latin-1"))

    # Objects: 1 catalog, 2 page tree, 3-4 fonts, then a page + content per page
    objects = [None, None]
    objects.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica "
                   b"/Encoding /WinAnsiEncoding >>")
    objects.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold "
                   b"/Encoding /WinAnsiEncoding >>")

    page_ids = []
    for stream in streams:
        data = zlib.compress(stream)
        content_id = len(objects) + 2
        page_ids.append(len(objects) + 1)
        objects.append((
            "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 %d %d] "
            "/Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> "
            "/Contents %d 0 R >>" % (PAGE_WIDTH, PAGE_HEIGHT, content_id)
        ).encode())
        objects.append(
            b"<< /Length %d /Filter /FlateDecode >>\nstream\n" % len(data)
            + data + b"\nendstream"
        )

    objects[0] = b"<< /Type /Catalog /Pages 2 0 R >>"
    objects[1] = ("<< /Type /Pages /Kids [%s] /Count %d >>" % (
        " ".join("%d 0 R" % page_id for page_id in page_ids), len(page_ids)
    )).encode()

    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % number + body + b"\nendobj\n"

    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objects) + 1)
    for offset in offsets:
        out += b"%010d 00000 n \n" % offset
    out += (b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n"
            % (len(objects) + 1, xref))

    return bytes(out)
